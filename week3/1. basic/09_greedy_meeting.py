"""
[그리디 - 회의실 배정]

문제 설명:
- 하나의 회의실에 여러 회의를 배정합니다.
- 각 회의는 시작 시간과 종료 시간이 있습니다.
- 최대한 많은 회의를 배정하려고 합니다.

입력:
- meetings: [(시작, 종료), ...] 회의 리스트

출력:
- 배정된 회의 개수

예제:
입력: [(1, 4), (3, 5), (0, 6), (5, 7), (3, 8), (5, 9), (6, 10), (8, 11), (8, 12), (2, 13), (12, 14)]
출력: 4개
선택: [(1, 4), (5, 7), (8, 11), (12, 14)]

힌트:
- 종료 시간이 빠른 회의부터 선택! -> 최대한 많이 채워넣으려고
- 이전 회의가 끝난 후에 시작하는 회의만 선택
"""


# 이중리스트에서 정렬하기
# lambda x:x[1] -> 익명 함수 생성
# 세가지 기준 1. 시작빠른순 2. 길이 짧은 순 3. 종료 시간 빠른 순
# 1 반례 : 시작시간이 빨라도 종료가 느리면 다른 항목들을 넣을수가 없음.
# 2 반례 : (6,8),(1,6)(7,12) 사례에서 회의시간 짧은 6,8 선택하니 2가지 선택지가 막힘. -> X -> (10,15) 를 선택한다 했을 때 어떤 값들을 비교했는지? 생각하기.
# 어떤걸 고르던간에, 그 다음에 선택할 숫자는 앞전 선택의 종료시간에 달려있음. -> 종료시간 비교. (그럼 어떨 때 더 유리한지?) -> 종료시간이 작을 때 더 유리함 

# 떠오르는 정렬 기준을 전부 적는다
# 각각을 반례로 죽여본다
# 살아남은 기준에 대해 남는 정보가 무엇인가 확인
# 어떤 선택을 하든 얻는 이득이 같은가 (같으면 그리디, 다르면 DP로 간다)
def select_meetings(meetings):
    """
    회의실 배정 (그리디)
    
    Args:
        meetings: [(시작, 종료)] 리스트
    
    Returns:
        (배정된 회의 개수, 선택된 회의 리스트)
    """
    # TODO: 회의가 없으면 0 반환
    if meetings is None:
        return 0
    
    # TODO: 종료 시간 기준으로 정렬
    meetings.sort(key = lambda x:x[1])
    
    selected = []
    
    # TODO: 첫 번째 회의 선택
    selected.append(meetings[0])
    
    # TODO: 나머지 회의들 확인
    ## 이전 회의가 끝난 후 시작하는 회의만 선택
    
    # 전체 회의를 돌면서
    for i,j in meetings:
        #  앞전 회의의 종료시간 < 시작시간 인 케이스만 조회 
        
        # 앞전 선택된 회의의 종료시간
        end_time = selected[len(selected) - 1][1]
        
        # 현재 회의의 시작시간
        start_time = i
        if start_time > end_time :
            selected.append((i,j))
        
    
    return len(selected), selected

